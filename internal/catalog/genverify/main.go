// Command genverify performs the live GET probes behind the site catalog.
//
// It is networked and is never run by "go generate". Run it by hand when the
// verification table needs a refresh:
//
//	go run ./internal/catalog/genverify
//
// The command tests every public and semi-private site from the manager
// snapshots, every private site whose family has public evidence, and the
// manual rows. It only issues GET requests; it never logs in, posts or
// downloads a torrent. The result is committed as metadata/verification.yaml
// and is the only source of "verificata" claims for lightweight rows.
package main

import (
	"context"
	"crypto/tls"
	"encoding/json"
	"flag"
	"fmt"
	"io"
	"net/http"
	"net/url"
	"os"
	"path/filepath"
	"regexp"
	"sort"
	"strings"
	"sync"
	"time"

	"gopkg.in/yaml.v3"

	"github.com/buzzqw/indexarr/internal/catalog"
	"github.com/buzzqw/indexarr/internal/catalog/managerdata"
)

const userAgent = "Mozilla/5.0 (X11; Linux x86_64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/125.0 Safari/537.36"

type snapshot struct {
	Schema  int                          `json:"schema"`
	Source  string                       `json:"source"`
	Fetched string                       `json:"fetched"`
	Sites   []managerdata.CatalogIndexer `json:"sites"`
}

type familyManifest struct {
	Families map[string]struct {
		Family   string `yaml:"family"`
		Evidence string `yaml:"evidence"`
	} `yaml:"families"`
}

type manualManifest struct {
	Sites []catalog.Site `yaml:"sites"`
}

type verification struct {
	URL      string   `yaml:"url"`
	HTTP     int      `yaml:"http,omitempty"`
	Final    string   `yaml:"final,omitempty"`
	Title    string   `yaml:"title,omitempty"`
	Bytes    int64    `yaml:"bytes,omitempty"`
	Families []string `yaml:"families,omitempty"`
	Checked  string   `yaml:"checked"`
	Error    string   `yaml:"error,omitempty"`
}

type resultManifest struct {
	Schema  int                     `yaml:"schema"`
	Checked string                  `yaml:"checked"`
	Method  string                  `yaml:"method"`
	Results map[string]verification `yaml:"results"`
}

type target struct {
	key      string
	source   string
	id       string
	url      string
	typeName string
}

func main() {
	dir := flag.String("metadata", "internal/catalog/metadata", "metadata directory")
	out := flag.String("out", "internal/catalog/metadata/verification.yaml", "output file")
	workers := flag.Int("workers", 12, "parallel GET probes")
	timeout := flag.Duration("timeout", 12*time.Second, "per-request timeout")
	probeAll := flag.Bool("all", false, "also probe private sources and sources with no known family")
	flag.Parse()

	jackett := loadSnapshot(filepath.Join(*dir, "jackett.json"))
	prowlarr := loadSnapshot(filepath.Join(*dir, "prowlarr.json"))
	families := loadFamilies(filepath.Join(*dir, "families.yaml"))
	manual := loadManual(filepath.Join(*dir, "manual.yaml"))

	targets := collectTargets(jackett, prowlarr, families, manual, *probeAll)
	if len(targets) == 0 {
		fmt.Fprintln(os.Stderr, "genverify: no targets")
		os.Exit(2)
	}

	ctx, cancel := context.WithCancel(context.Background())
	defer cancel()
	client := &http.Client{
		Timeout: *timeout,
		Transport: &http.Transport{
			TLSClientConfig:     &tls.Config{InsecureSkipVerify: true},
			MaxIdleConnsPerHost: 2,
		},
		CheckRedirect: func(req *http.Request, via []*http.Request) error {
			if len(via) >= 8 {
				return http.ErrUseLastResponse
			}
			return nil
		},
	}

	results := make(map[string]verification, len(targets))
	var mu sync.Mutex
	sem := make(chan struct{}, max(1, *workers))
	var wg sync.WaitGroup
	for _, item := range targets {
		if ctx.Err() != nil {
			break
		}
		wg.Add(1)
		go func(item target) {
			defer wg.Done()
			sem <- struct{}{}
			defer func() { <-sem }()
			value := probe(ctx, client, item)
			mu.Lock()
			results[item.key] = value
			mu.Unlock()
		}(item)
	}
	wg.Wait()

	now := time.Now().UTC().Format("2006-01-02")
	manifest := resultManifest{
		Schema:  1,
		Checked: now,
		Method:  "GET homepage, redirects followed, no login",
		Results: results,
	}
	body, err := yaml.Marshal(manifest)
	if err != nil {
		fmt.Fprintf(os.Stderr, "genverify: encode: %v\n", err)
		os.Exit(1)
	}
	header := "# Generated by go run ./internal/catalog/genverify. DO NOT EDIT.\n#\n# Live GET evidence for the lightweight catalog rows. A row is only\n# \"verificata\" when this table has a successful GET; private sites stay\n# \"da-provvi\" even when their login page answers.\n"
	if err := os.MkdirAll(filepath.Dir(*out), 0o755); err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
	if err := os.WriteFile(*out, append([]byte(header), body...), 0o644); err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
	ok, failed := 0, 0
	for _, value := range results {
		if value.Error == "" && value.HTTP >= 200 && value.HTTP < 400 {
			ok++
		} else {
			failed++
		}
	}
	fmt.Printf("verified live: %d, failed/blocked: %d, total: %d\n", ok, failed, len(results))
}

func collectTargets(jackett, prowlarr snapshot, families familyManifest, manual manualManifest, probeAll bool) []target {
	var out []target
	seenURL := map[string]bool{}
	add := func(item target) {
		key := normalizeURL(item.url)
		if key != "" && seenURL[key] {
			return
		}
		if key != "" {
			seenURL[key] = true
		}
		out = append(out, item)
	}
	for _, site := range jackett.Sites {
		include := probeAll || site.Type == "public" || site.Type == "semi-private"
		if _, ok := families.Families[site.SourceID]; ok {
			include = true
		}
		if !include {
			continue
		}
		add(target{key: "jackett:" + site.SourceID, source: "jackett", id: site.SourceID, url: site.URL, typeName: site.Type})
	}
	for _, site := range prowlarr.Sites {
		add(target{key: "prowlarr:" + site.SourceID, source: "prowlarr", id: site.SourceID, url: site.URL, typeName: site.Type})
	}
	for _, site := range manual.Sites {
		add(target{key: "manual:" + site.ID, source: "manual", id: site.ID, url: site.URL, typeName: site.Type})
	}
	sort.SliceStable(out, func(i, j int) bool { return out[i].key < out[j].key })
	return out
}

func probe(ctx context.Context, client *http.Client, item target) verification {
	value := verification{URL: item.url, Checked: time.Now().UTC().Format("2006-01-02")}
	if strings.TrimSpace(item.url) == "" {
		value.Error = "no URL"
		return value
	}
	var lastErr error
	for attempt := 0; attempt < 2; attempt++ {
		if ctx.Err() != nil {
			value.Error = "cancelled"
			return value
		}
		request, err := http.NewRequestWithContext(ctx, http.MethodGet, item.url, nil)
		if err != nil {
			value.Error = "invalid request"
			return value
		}
		request.Header.Set("User-Agent", userAgent)
		request.Header.Set("Accept", "text/html,application/xhtml+xml,application/xml;q=0.9,*/*;q=0.8")
		request.Header.Set("Accept-Language", "en-US,en;q=0.9,it;q=0.8")
		response, err := client.Do(request)
		if err != nil {
			lastErr = err
			time.Sleep(400 * time.Millisecond)
			continue
		}
		body, readErr := io.ReadAll(io.LimitReader(response.Body, 256<<10))
		response.Body.Close()
		if readErr != nil {
			lastErr = readErr
			continue
		}
		value.HTTP = response.StatusCode
		value.Final = response.Request.URL.String()
		value.Bytes = int64(len(body))
		value.Title = htmlTitle(body)
		value.Families = familyMarkers(body)
		return value
	}
	if lastErr != nil {
		value.Error = shortError(lastErr)
	}
	return value
}

var titlePattern = regexp.MustCompile(`(?is)<title[^>]*>(.*?)</title>`)

func htmlTitle(body []byte) string {
	match := titlePattern.FindSubmatch(body)
	if len(match) < 2 {
		return ""
	}
	title := string(match[1])
	title = strings.Join(strings.Fields(title), " ")
	if len(title) > 160 {
		title = title[:160]
	}
	return title
}

func familyMarkers(body []byte) []string {
	text := strings.ToLower(string(body))
	var out []string
	// Only markers that name the software or one of its distinctive paths are
	// used. Weak generic paths (getrss.php, ajax.php?action, download.php?id=)
	// appear on several families and would mislabel a site; a wrong family is
	// worse than a source queued for a written definition.
	for family, markers := range map[string][]string{
		catalog.FamilyUnit3D:        {"unit3d", "api/torrents", "/api/v1/torrents"},
		catalog.FamilyGazelle:       {"gazelle", "torrents.php?action=torrents"},
		catalog.FamilyNexusPHP:      {"nexusphp"},
		catalog.FamilyTorrentTrader: {"torrenttrader", "torrent trader"},
		catalog.FamilyXbtit:         {"xbtit", "btiteam", "xbtitfm", "jscript/xbtit.js"},
	} {
		for _, marker := range markers {
			if strings.Contains(text, marker) {
				out = append(out, family)
				break
			}
		}
	}
	sort.Strings(out)
	return out
}

func shortError(err error) string {
	text := err.Error()
	if urlErr, ok := err.(*url.Error); ok && urlErr.Err != nil {
		text = urlErr.Err.Error()
	}
	if len(text) > 160 {
		text = text[:160]
	}
	return text
}

func normalizeURL(raw string) string {
	parsed, err := url.Parse(strings.TrimSpace(raw))
	if err != nil || parsed.Host == "" {
		return ""
	}
	host := strings.TrimPrefix(strings.ToLower(parsed.Hostname()), "www.")
	return parsed.Scheme + "://" + host + strings.TrimRight(parsed.Path, "/")
}

func loadSnapshot(path string) snapshot {
	body, err := os.ReadFile(path)
	if err != nil {
		fmt.Fprintf(os.Stderr, "genverify: %v\n", err)
		os.Exit(1)
	}
	var value snapshot
	if err := json.Unmarshal(body, &value); err != nil {
		fmt.Fprintf(os.Stderr, "genverify: %s: %v\n", path, err)
		os.Exit(1)
	}
	return value
}

func loadFamilies(path string) familyManifest {
	body, err := os.ReadFile(path)
	if err != nil {
		fmt.Fprintf(os.Stderr, "genverify: %v\n", err)
		os.Exit(1)
	}
	var value familyManifest
	if err := yaml.Unmarshal(body, &value); err != nil {
		fmt.Fprintf(os.Stderr, "genverify: %s: %v\n", path, err)
		os.Exit(1)
	}
	return value
}

func loadManual(path string) manualManifest {
	body, err := os.ReadFile(path)
	if err != nil {
		if os.IsNotExist(err) {
			return manualManifest{}
		}
		fmt.Fprintf(os.Stderr, "genverify: %v\n", err)
		os.Exit(1)
	}
	var value manualManifest
	if err := yaml.Unmarshal(body, &value); err != nil {
		fmt.Fprintf(os.Stderr, "genverify: %s: %v\n", path, err)
		os.Exit(1)
	}
	return value
}

func max(a, b int) int {
	if a > b {
		return a
	}
	return b
}
